// Regenerates src/generated/openapi.ts from docs/openapi.yaml.
//
// The first line records the SHA-256 of the spec it was generated from; the
// Go OpenAPI drift test (internal/server/openapi_test.go) and CI compare it
// with the current spec, so the committed types cannot fall behind.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, '../../docs/openapi.yaml');
const outPath = join(root, 'src/generated/openapi.ts');

const spec = readFileSync(specPath);
const sha = createHash('sha256').update(spec).digest('hex');
const ast = await openapiTS(pathToFileURL(specPath), {
  alphabetize: false,
  exportType: true,
});
const body = astToString(ast);
const header = [
  `// spec-sha256: ${sha}`,
  '// Code generated by scripts/generate.mjs from docs/openapi.yaml. DO NOT EDIT.',
  '// Regenerate with `npm run generate` in sdk/typescript.',
  '',
].join('\n');
writeFileSync(outPath, header + body);
console.log(`wrote ${outPath} (spec ${sha.slice(0, 12)})`);
