package store

import (
	"time"
)

// ACMELEAccount is a persisted ACME (Let's Encrypt) account, scoped to a single
// ACME directory URL. The account private key is stored wrapped, using the same
// envelope scheme as KMS key material.
type ACMELEAccount struct {
	ID           string
	DirectoryURL string
	AccountURI   string
	ContactEmail string
	// AccountKeyDER is the unwrapped PKCS#8 account private key. It is only
	// populated in memory; the store wraps it before persisting.
	AccountKeyDER []byte
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

// ACMELECertificate is a publicly-trusted certificate obtained from Let's
// Encrypt. Unlike pcaCertificate it has no local issuing CA; the private key is
// generated by Citadel and stored wrapped so operators can download it.
type ACMELECertificate struct {
	CertID       string
	DirectoryURL string
	Domains      string
	Serial       string
	CertB64      string
	ChainB64     string
	// KeyDER is the unwrapped PKCS#8 leaf private key, populated in memory only.
	KeyDER    []byte
	Status    string
	NotBefore time.Time
	NotAfter  time.Time
	CreatedAt time.Time
	UpdatedAt time.Time
}

// ACMELEOrder is an in-flight ACME order awaiting manual DNS-01 validation. It
// persists the order URL (and owning account) between the "begin" request that
// returns the TXT records to publish and the "complete" request that finalizes
// issuance once the operator has added them at their DNS provider.
type ACMELEOrder struct {
	OrderID      string
	OrderURL     string
	DirectoryURL string
	Domains      string
	Status       string
	CreatedAt    time.Time
	ExpiresAt    time.Time
}
