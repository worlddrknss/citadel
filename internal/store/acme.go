package store

import (
	"time"
)

// ACMELEAccount is a persisted ACME (Let's Encrypt) account, scoped to a single
// ACME directory URL. The account private key is stored wrapped, using the same
// envelope scheme as KMS key material.
type ACMELEAccount struct {
	ID           string
	DirectoryURL string
	AccountURI   string
	ContactEmail string
	// AccountKeyDER is the unwrapped PKCS#8 account private key. It is only
	// populated in memory; the store wraps it before persisting.
	AccountKeyDER []byte
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

// ACMELECertificate is a publicly-trusted certificate obtained from Let's
// Encrypt. Unlike pcaCertificate it has no local issuing CA; the private key is
// generated by Citadel and stored wrapped so operators can download it.
type ACMELECertificate struct {
	CertID       string
	DirectoryURL string
	Domains      string
	Serial       string
	CertB64      string
	ChainB64     string
	// KeyDER is the unwrapped PKCS#8 leaf private key, populated in memory only.
	KeyDER    []byte
	Status    string
	NotBefore time.Time
	NotAfter  time.Time
	CreatedAt time.Time
	UpdatedAt time.Time

	// AccountID is the owning tenant; set by the store on reads.
	AccountID string
	// ChallengeKind is how it was validated: http-01, dns-01, or "" for
	// certificates issued before Citadel recorded it.
	ChallengeKind string
	// AutoRenew: renew automatically (HTTP-01 only) 30 days before expiry.
	AutoRenew bool
	// Automatic renewal state: failed attempts since the last success, when
	// the next attempt may run, the last attempt and its error, and the
	// certificate that replaced this one.
	RenewAttempts      int
	RenewNextAttemptAt *time.Time
	RenewLastAttemptAt *time.Time
	RenewLastError     string
	RenewedBy          string
}

// ACMELEOrder is a Let's Encrypt order. Issuance runs in the background (it
// can take minutes), so the order row carries its progress for the console
// to poll: Status is pending (DNS-01: waiting for the operator to publish
// the TXT records), processing, issued (CertID set) or failed (Error set).
// For DNS-01 it also persists the order URL between the "begin" request that
// returns the TXT records and the "complete" request.
type ACMELEOrder struct {
	OrderID      string
	OrderURL     string
	DirectoryURL string
	Domains      string
	Status       string
	// Kind is http-01 or dns-01.
	Kind      string
	Progress  string
	Error     string
	CertID    string
	CreatedAt time.Time
	UpdatedAt time.Time
	ExpiresAt time.Time
}

// Let's Encrypt order statuses and kinds.
const (
	ACMELEOrderPending    = "pending"
	ACMELEOrderProcessing = "processing"
	ACMELEOrderIssued     = "issued"
	ACMELEOrderFailed     = "failed"

	ACMELEOrderHTTP01 = "http-01"
	ACMELEOrderDNS01  = "dns-01"
)
